    private static void deepToString(Object[] objectArray, StringBuffer stringBuffer, List list) {
        list.add(objectArray);
        stringBuffer.append('[');
        for (int i2 = 0; i2 < objectArray.length; ++i2) {
            Object object;
            if (i2 > 0) {
                stringBuffer.append(", ");
            }
            if ((object = objectArray[i2]) == null) {
                stringBuffer.append("null");
                continue;
            }
            if (!object.getClass().isArray()) {
                stringBuffer.append(object.toString());
                continue;
            }
            if (object instanceof Object[]) {
                if (list.contains(object)) {
                    stringBuffer.append("[...]");
                    continue;
                }
                Arrays.deepToString((Object[])object, stringBuffer, list);
                continue;
            }
            stringBuffer.append(object instanceof byte[] ? Arrays.toString((byte[])object) : (object instanceof short[] ? Arrays.toString((short[])object) : (object instanceof int[] ? Arrays.toString((int[])object) : (object instanceof long[] ? Arrays.toString((long[])object) : (object instanceof char[] ? Arrays.toString((char[])object) : (object instanceof boolean[] ? Arrays.toString((boolean[])object) : (object instanceof float[] ? Arrays.toString((float[])object) : (object instanceof double[] ? Arrays.toString((double[])object) : ""))))))));
        }
        stringBuffer.append(']');
        list.remove(list.size() - 1);
    }
